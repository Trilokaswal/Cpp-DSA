// Bool data type is used to store boolean values, which can be either true or false.
// it gives 1 for true and 0 for false.
// it is used to find the state of a condition, whether it is true or false.

#include <iostream>
using namespace std;

int main () { 

    bool isCodingFun = true;
    bool isFishTasty = false;

    cout << "Is coding fun? " << isCodingFun << endl; // Output: 1
    cout << "Is fish tasty? " << isFishTasty << endl; // Output: 0

    return 0;

}