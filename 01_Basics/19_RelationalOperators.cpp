// Relational operators are used to compare two values.
// They return a boolean value (true or false) based on the comparison.

// The following are the relational operators in C++:
// 1. Equal to (==)
// 2. Not equal to (!=)
// 3. Greater than (>)
// 4. Less than (<)
// 5. Greater than or equal to (>=)
// 6. Less than or equal to (<=)

// These operators are commonly used in conditional statements
// and loops to control the flow of the program.

#include <iostream>
using namespace std;

int main () {

    int a = 10;
    int b = 20;

    bool x = (a==b);
    cout << x << endl;

    return 0;
    
}