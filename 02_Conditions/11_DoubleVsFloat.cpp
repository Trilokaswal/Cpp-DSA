// difference between FLOAT AND DOUBLE DATA TYPES

// Float and double are both data types used to store decimal (floating-point) numbers.

// float: It stores decimal values using less memory, 
// usually 4 bytes, but provides lower precision of about 6–7 digits.

// double: It stores decimal values using more memory, usually 8 bytes which means 64-bits
// but provides higher precision of about 15–16 digits.

// Difference:
// float → 4 bytes, lower precision
// double → 8 bytes, higher precision

// Example:
// float a = 3.14;
// double b = 3.1415926535;

// In general, double is preferred when higher precision is required.



